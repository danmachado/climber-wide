const { chromium } = require('playwright');
const mock = require('./mock.js');
(async () => {
  await mock.start(8791);
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' }).catch(() => chromium.launch());
  const ctx = await b.newContext({ viewport: { width: 1280, height: 1100 } });
  await ctx.addInitScript(() => { window.CLIMBER_BACKEND = { url: 'http://localhost:8791', key: 'k' }; });
  const p = await ctx.newPage();
  const errs = []; p.on('pageerror', e => errs.push(String(e)));
  const status = async () => (await p.locator('#status').innerText());
  const gamePool = async () => { const g = await ctx.newPage(); await g.goto('file:///home/claude/climber-wide/index.html'); await g.waitForTimeout(700);
    const r = await g.evaluate(() => { window.__climber.reset(); return document.title && JSON.parse(localStorage.getItem('climber.live.v1') || '[]').map(x => x.name); }); await g.close(); return JSON.stringify(r); };
  await p.goto('file:///home/claude/climber-wide/builder/index.html');
  await p.fill('#p-email', 'dan@example.com'); await p.fill('#p-pass', 'wrong'); await p.click('#p-in'); await p.waitForTimeout(300);
  console.log('1 wrong password ->', await status());
  await p.fill('#p-pass', 'pw'); await p.click('#p-in'); await p.waitForTimeout(400);
  console.log('2 not admin yet -> setup shown:', await p.locator('#p-setup').isVisible(), '|', (await p.inputValue('#p-sql')).replace(/\n/g, ' '));
  mock.db.admins.push('u1'); await p.click('#p-recheck'); await p.waitForTimeout(400);
  console.log('3 admin -> main shown:', await p.locator('#p-main').isVisible());
  await p.click('#p-publish'); await p.waitForTimeout(300);
  console.log('4 publish before beating ->', await status());
  await p.click('#p-save'); await p.waitForTimeout(500);
  console.log('5 save draft ->', await status(), '| rooms:', await p.locator('#p-rooms').innerText(), '| game sees:', await gamePool());
  await p.click('#play'); await p.waitForTimeout(1200);
  const fr = p.frames().find(f => f.url().endsWith('/climber/index.html'));
  await fr.evaluate(() => { window.__climber.manual(true); window.__climber.demoRun(3000); window.__climber.manual(false); });
  await p.waitForTimeout(300); await p.click('#play');
  await p.click('#p-publish'); await p.waitForTimeout(600);
  console.log('6 publish ->', await status(), '| rooms:', await p.locator('#p-rooms').innerText(), '| game sees:', await gamePool());
  // edit, beat again, publish v2, then roll back to v1
  await p.fill('#name', 'First Light Two'); await p.dispatchEvent('#name', 'input');
  await p.evaluate(() => {}); 
  await p.click('#play'); await p.waitForTimeout(1200);
  const fr2 = p.frames().find(f => f.url().endsWith('/climber/index.html'));
  await fr2.evaluate(() => { window.__climber.manual(true); window.__climber.demoRun(3000); window.__climber.manual(false); });
  await p.waitForTimeout(300); await p.click('#play');
  await p.click('#p-publish'); await p.waitForTimeout(600);
  console.log('7 publish again ->', await status(), '| versions:', (await p.locator('#p-vers').innerText()).replace(/\n/g, ' / '), '| game sees:', await gamePool());
  const oldest = await p.locator('#p-vers option').nth(1).getAttribute('value');
  await p.selectOption('#p-vers', oldest); await p.click('#p-roll'); await p.waitForTimeout(500);
  console.log('8 roll back ->', await status(), '| live version is the first publish:', mock.db.rooms[0].published_version_id === mock.db.versions.filter(v => v.validated)[0].id, '| game sees:', await gamePool());
  await p.click('#p-unpub'); await p.waitForTimeout(500);
  console.log('9 unpublish ->', await status(), '| game sees:', await gamePool());
  await p.screenshot({ path: 'pub.png', clip: { x: 0, y: 560, width: 290, height: 540 } });
  console.log('db rooms', mock.db.rooms.length, 'versions', mock.db.versions.length, 'errors', JSON.stringify(errs));
  await b.close(); process.exit(0);
})();
